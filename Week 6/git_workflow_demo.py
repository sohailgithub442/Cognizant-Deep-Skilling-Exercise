"""
Git Workflow Demonstration

1. Create Repository
   git init

2. Create Main Branch
   git add .
   git commit -m "Initial Commit"

3. Create Feature Branch
   git checkout -b feature/add-functions

4. Add New Feature
   (Example: subtract function)
   git add .
   git commit -m "Added subtract function"

5. Push Branch
   git push origin feature/add-functions

6. Create Pull Request on GitHub

7. If Merge Conflict Occurs:
   - Edit conflicting lines
   - Save the file
   - git add .
   - git commit -m "Resolved Merge Conflict"

8. Merge into Main
"""

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

print("Addition:", add(20, 10))
print("Subtraction:", subtract(20, 10))
